import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {JSDOM} from 'jsdom';
import english from '../extension/locales/en.js';

const root=new URL('../',import.meta.url),file=new URL('extension/popup-boot.js',root);
const marker='// END GENERATED POPUP LOCALE\n';
const original=fs.readFileSync(file,'utf8').replaceAll('\r\n','\n');
const body=original.includes(marker)?original.split(marker)[1]:original;
const dom=new JSDOM(fs.readFileSync(new URL('extension/popup.html',root),'utf8'));
const keys=new Set();
for(const element of dom.window.document.querySelectorAll('*'))for(const attr of element.attributes)if(attr.name==='data-i18n'||attr.name.startsWith('data-i18n-')&&attr.name!=='data-i18n-once')keys.add(attr.value);
for(const key of ['保存功能暂时无法加载，可先打开我的收藏。','尚未完成','页面载入：{0} 毫秒；网页识别：{1} 毫秒。此计时不包含 Chrome 创建窗口之前的等待。'])keys.add(key);
dom.window.close();
for(const key of keys)if(!Object.hasOwn(english,key))throw new Error('Missing popup translation: '+key);
const messages=Object.fromEntries([...keys].sort().map(key=>[key,english[key]]));
const generated=`// Generated by scripts/build_popup_locale.mjs. Keep the cold popup independent of modules and IndexedDB.
(()=>{
  const key='bookmark-house-language',messages=${JSON.stringify(messages)};
  let language='zh-CN';
  try{language=/^zh(?:[-_]|$)/i.test(navigator.language)?'zh-CN':'en';const saved=localStorage.getItem(key);if(saved==='en'||saved==='zh-CN')language=saved;}catch{}
  const t=source=>language==='en'?(messages[source]??source):source;
  const msg=(parts,...values)=>t(parts.reduce((text,part,index)=>text+(index?'{'+(index-1)+'}':'')+part,'')).replace(/\\{(\\d+)\\}/g,(_,index)=>String(values[index]??''));
  function apply(){
    document.documentElement.lang=language;
    for(const el of document.querySelectorAll('[data-i18n]')){el.textContent=t(el.dataset.i18n);if(el.hasAttribute('data-i18n-once')){el.removeAttribute('data-i18n');el.removeAttribute('data-i18n-once');}}
    for(const attr of ['title','placeholder','aria-label','alt'])for(const el of document.querySelectorAll('[data-i18n-'+attr+']'))el.setAttribute(attr,t(el.getAttribute('data-i18n-'+attr)));
    for(const select of document.querySelectorAll('[data-language-select]')){select.value=language;select.dataset.shellLanguage='';}
  }
  function setLanguage(value,persist=true){
    const next=/^zh(?:[-_]|$)/i.test(value)?'zh-CN':'en',changed=language!==next;language=next;
    if(persist){try{localStorage.setItem(key,next);}catch{}try{const job=globalThis.chrome?.runtime?.sendMessage?.({type:'bookmark-house-language',language:next});job?.catch?.(()=>{});}catch{}}
    apply();if(changed)window.dispatchEvent(new CustomEvent('bookmark-house-language-change',{detail:next}));
  }
  window.BookmarkHouseShell={get language(){return language;},t,msg,setLanguage};
  document.addEventListener('change',event=>{if(event.target.matches?.('[data-language-select]'))setLanguage(event.target.value);});
  window.addEventListener('storage',event=>{if(event.key===key&&event.newValue)setLanguage(event.newValue,false);});
  apply();
})();
${marker}`;
const expected=generated+body;
if(process.argv.includes('--check')){
  if(expected!==original)throw new Error('Popup translations are stale. Run npm run build:locales.');
}else fs.writeFileSync(file,expected);
console.log(JSON.stringify({popup_messages:keys.size,cold_locale_bytes:Buffer.byteLength(generated),file:fileURLToPath(file)}));
